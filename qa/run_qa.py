"""One command for the whole automated QA gate: lint, tests, selftest, screenshots, balance. Writes qa/RESULTS.md.
Run:  .venv/bin/python qa/run_qa.py"""
import os
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PY = sys.executable
STEPS = [
    ("lint (ruff)", [PY, "-m", "ruff", "check", "."]),
    ("tests (pytest)", [PY, "-m", "pytest"]),
    ("selftest (headless smoke)", [PY, "main.py", "--selftest"]),
    ("screenshots", [PY, "qa/render_shots.py"]),
    ("sprite sheet", [PY, "qa/render_sprites.py"]),
    ("balance, content only (multipliers off)", [PY, "qa/balance.py", "4", "careful", "--flat"]),
    ("balance, with the per-level multipliers", [PY, "qa/balance.py", "4", "careful"]),
]


def main():
    lines, ok = ["# Automated QA results", "", f"Generated by `qa/run_qa.py` on {time.strftime('%Y-%m-%d %H:%M')}.", ""], True
    for name, cmd in STEPS:
        t0 = time.time()
        p = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, env={**os.environ, "SDL_VIDEODRIVER": "dummy", "SDL_AUDIODRIVER": "dummy"})
        good = p.returncode == 0
        ok &= good
        out = (p.stdout + p.stderr).strip().splitlines()
        tail = [l for l in out if not l.startswith(("pygame ", "Hello from"))][-14 if "balance" in name else -4:]
        print(f"{'PASS' if good else 'FAIL'}  {name}  ({time.time() - t0:.1f}s)")
        lines += [f"## {'PASS' if good else 'FAIL'}: {name} ({time.time() - t0:.1f}s)", "", "```", *tail, "```", ""]
    open(os.path.join(ROOT, "qa", "RESULTS.md"), "w").write("\n".join(lines))
    print("wrote qa/RESULTS.md")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
